import streamlit as st

# إعدادات صفحة ستريمليت
st.set_page_config(
    page_title="موسوعة التراث والثقافة السعودية الشاملة",
    page_icon="🏛️",
    layout="centered",
)

st.title("🏛️ موسوعة التراث والثقافة السعودية")
st.write(
    "حيّاك الله في مجلس التاريخ والأصالة! اسألي عن أي مدينة أو منطقة أو عادة"
    " تراثية في المملكة وسأروي لك قصتها بتفاصيلها العميقة."
)

# إدارة سجل المحادثة
if "messages" not in st.session_state:
  st.session_state.messages = []

# عرض رسائل الشات السابقة
for message in st.session_state.messages:
  with st.chat_message(message["role"]):
    st.markdown(message["content"])


# دالة ذكية وعميقة جداً لتقديم معلومات تاريخية وتراثية غنية ودقيقة
def get_deep_cultural_response(query):
  q = query.lower()

  if (
      any(w in q for w in ["أبها", "عسير", "الجنوب", "السروات", "رجال ألمع"])
      or "عسير" in q
  ):
    return """### 🏔️ عروس السحاب: عسير التاريخ والأصالة
عسير ليست مجرد منطقة طبيعية، بل هي متحف تاريخي مفتوح يمتد عبقها لأمم غابرة:
* **العمارة التاريخية:** تتميز بيوت رجال ألمع والقرى التراثية بـ "القصبات" الحجرية المرتفعة والمدعمة بصفوف من حجر "الكوارتز" الأبيض لتصريف مياه الأمطار، وهي هندسة معمارية فريدة تتحدى الزمن.
* **الفنون والأزياء:** تشتهر بفن "القط العسيري" (وهو فن هندسي نقشي أدرجته اليونسكو في التراث العالمي، تفرضه النساء بمهارة على جدران المجالس الداخلية)، إضافة إلى العرضة الجنوبية وللبس التقليدي المزرزب والمحرز.
* **المطبخ العسيري:** من أعرق الأكلات: *العريكة*، *المصابيب*، *الحنيذ* المبني على المحاذي الحجرية، و*المخشوش*.
* **القصيد والأمثال:** ارتبطت جبال السروات بأهازيج الحصاد والزواجات التي تبث الحماس والكرم."""

  elif (
      any(w in q for w in ["نجد", "الرياض", "الدرعية", "القصيم", "حائل", "العلا"])
      or "نجد" in q
  ):
    return """### 🏜️ قلب المملكة النابض: نجد العذية والتاريخ العريق
نجد هي موطن الأمجاد والقصص التي خلدها التاريخ والشعر:
* **الدرعية التاريخية:** منبع الدولة السعودية الأولى، وتتميز بحي طريف ومعماره الطيني المهيب المبني على ضفاف وادي حنيفة.
* **الأعراف والشهامة:** عُرف أهل نجد بـ "السامري" و"العرضة النجدية"، وضرب المثل بكرم الضيافة وتقديم دلة القهوة الهيل والزعفران مع التمر السكري أو الصقعي.
* **المطبخ النجدي:** *الجريش*، *المرقوق*، *المطازيز*، و*الحنيني* الشتوي الذي يدفئ المجالس.
* **الأمثال والقصائد:** نجد غنية بالقصائد النبطية الخالدة لشعراء مثل ابن سبيل وغيرهم، وتوثق شجاعة الفرسان وقصص الحين والفروسية."""

  elif (
      any(
          w in q
          for w in [
              "الحجاز",
              "جدة",
              "مكة",
              "المدينة",
              "الطائف",
              "ينبع",
              "البلد",
          ]
      )
      or "الحجاز" in q
  ):
    return """### 🌊 عروس البحر ومهبط الوحي: الحجاز التاريخي
الحجاز هو ملتقى الثقافات الإسلامية والعربية نظراً لمرور الحجاج والمعتمرين عبر التاريخ:
* **الرواشين الحجازية:** تتميز مدينة "جدة التاريخية" (البلد) ببيوتها العتيقة ذات الرواشين الخشبية المزخرفة المصنوعة من خشب الجلوي والتي صممت بعبقرية لصد الحرارة وتلطيف الهواء.
* **الفنون والأهازيج:** تشتهر بالفنون البحرية مثل *السمسمية* و*الممج*، وفن *الخطوة* الحجازية، وتفاعل الثقافات الآسيوية والإفريقية مع التراث المحلي.
* **المأكولات الحجازية:** *السليق* الطائفي بالحليب والسمن البري، *المثلوثة*، *المينتو والجبات، والشوربة الحجازية الرمضانية."""

  elif (
      any(
          w in q
          for w in [
              "الشرقية",
              "الأحساء",
              "القطيف",
              "الدمام",
              "الخبر",
              "الواحة",
              "البشت",
          ]
      )
      or "الشرقية" in q
  ):
    return """### 🌴 واحات النخيل ولؤلؤ الخليج: المنطقة الشرقية
الشرقية تجمع بين عبق الصحراء وسحر الخليج العربي:
* **واحة الأحساء:** أكبر واحة نخيل أُحادية في العالم ومسجلة في اليونسكو، وتضم أكثر من 2.5 مليون نخة عريقة وعيون ماء كبريتية تاريخية مثل عين قحطان وفريحة.
* **الصناعات الحرفية:** صناعة *البشت الحساوي* المصنوع من الصوف الخالص والخيوط الذهبية (الزري)، وصناعة الفخار التقليدي في مدرسة القارة.
* **الفنون البحرية:** فنون الغوص على اللؤلؤ مثل *الفجري*، و*الصوت*، و*السامري الشرقي*، وأكلات مثل *المحمر* و*الصالونة الحساوية*."""

  elif any(
      w in q
      for w in [
          "الشمال",
          "تبوك",
          "الجوف",
          "عرعر",
          "سكاكا",
          "حطين",
          "القلعة",
          "دومة",
      ]
  ):
    return """### ⛰️ بوابات الشمال وعراقة القلاع التاريخية
الشمال السعودي يتميز بتاريخ موغل في القدم وآثار مذهلة:
* **دومة الجندل وجبل أم سنمان:** قلعة مارد التاريخية ومسجد عمر بن الخطاب رضي الله عنه بمدينته العريقة في الجوف، شواهد حية على الحضارات القديمة.
* **الطبيعة والتراث:** أشجار الزيتون التاريخية في الجوف، وقلاع تبوك العثمانية، ونقوش الرجاجيل الأثرية التي تعود لآلاف السنين قبل الميلاد.
* **الكرم والشعر:** تشتهر ديار الشمال بالربابة وقصص الهيل والقهوة وقرى الرحالة القدامى."""

  elif any(w in q for w in ["جازان", "الوجه", "فرسان", "الباحة"]):
    return """### 🌺 لؤلؤة الجنوب وبساتين الباحة
* **منطقة جازان:** تشتهر بالقلاع التاريخية في جزر فرسان، والمدرجات الزراعية العطرية التي تُزرع فيها الفل والكادي والنباتات العطرية التي يزين بها أهالي جازان رؤوسهم في الأعياد والمناسبات (*العصابة الريثية*).
* **منطقة الباحة:** غابات الأعرج وقرى ذي عين التاريخية المبنية من الحجارة على سفح جبل أبيض والتي تتدفق من عيونها المياه العارية بلا انقطاع."""

  else:
    return f"""### 🏛️ عبق التاريخ السعودي في كل زاوية
سؤالك عن **"{query}"** يلامس جانباً مهماً من إرثنا الثقافي العريق. 
المملكة العربية السعودية عبارة عن قارة مصغرة؛ فكل منطقة (نجد، الحجاز، عسير، الشرقية، الشمال، جازان، الباحة) تمتلك هويتها المعمارية، وفنونها الشعبية، وأهازيجها، وأكلاتها الخاصة التي تناقلتها الأجيال بوفاء وأصالة. 

تفضلي واسأليني عن أي مدينة محددة (مثل: أبها، الدرعية، الأحساء، جدة، الجوف...) لأفصل لك تاريخها وأسرارها بشكل دقيق وعميق!"""


# صندوق الإدخال للمستخدم
if prompt := st.chat_input(
    "اسأل عن أي مدينة، تراث، عادات، أو تاريخ في المملكة..."
):
  st.session_state.messages.append({"role": "user", "content": prompt})
  with st.chat_message("user"):
    st.markdown(prompt)

  with st.chat_message("assistant"):
    with st.spinner("جاري استحضار عمق التاريخ وتفاصيل التراث..."):
      answer = get_deep_cultural_response(prompt)
      st.markdown(answer)
      st.session_state.messages.append({"role": "assistant", "content": answer})
