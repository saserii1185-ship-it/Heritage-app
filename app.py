import streamlit as st

# إعدادات صفحة ستريمليت
st.set_page_config(
    page_title="موسوعة التراث والثقافة السعودية",
    page_icon="🏜️",
    layout="centered",
)

st.title("🏜️ موسوعة التراث والثقافة السعودية الشاملة")
st.write(
    "حيّاك الله في مجلس الأصيلة! هنا تجدين تفاصيل دقيقة تشمل المأكولات،"
    " العمارة، الأزياء، الشعر، وعادات الأولين، مع **توسع خاص وعميق في تراث"
    " نجد العذية**."
)

# إدارة سجل المحادثة
if "messages" not in st.session_state:
  st.session_state.messages = []

# عرض رسائل الشات السابقة
for message in st.session_state.messages:
  with st.chat_message(message["role"]):
    st.markdown(message["content"])


# دالة شاملة وعميقة تجمع الأكل وكل التفاصيل التراثية الإضافية
def get_cultural_response(query):
  q = query.lower()

  # التوسع العميق والشامل في نجد (الأكل + الأزياء + الشعر + العمارة + العادات)
  if (
      any(
          w in q
          for w in [
              "نجد",
              "الرياض",
              "الدرعية",
              "القصيم",
              "حائل",
              "الشقراء",
              "المجمعة",
              "العرضة",
              "الجريش",
              "الحنيني",
          ]
      )
      or "نجد" in q
  ):
    return """### 🏜️ موسوعة نجد العذية: المذاق، التاريخ، والأصالة
لأننا نتوسع في نجد، فهذه حقيبة متكاملة تضم الأكل وكل تفاصيل الحياة الاجتماعية والتراثية:

* **🍽️ المطبخ النجدي (الأكل على اصوله):**
  * *الجريش:* سيد السفرة النجدية، قمح مجروش بعناية يُطبخ مع اللبن واللحم، ويُقدح فوقه السمن البري والبصل المكرمل والبهارات الخاصة.
  * *المرقوق والمطازيز:* عجينة البر الممدودة بمهارة، تُطبخ في مرق اللحم مع الخضار الطازجة لتعطي نكهة لا تُنسى.
  * *الحنيني:* أكلة الشتاء الأولى، تُصنع من التمر الخلاص المفروم مع البر المفتوت والسمن البري والهيل.
  * *المفتاحة والحميس:* أطباق البدو الرحل التي تعتمد على لحم الإبل والسمن والقرص الجاف.

* **🏛️ العمارة الطينية الهندسية:**
  * تُبنى البيوت والقصور من "اللبن" (الطين المجفف بالشمس) وتُدعّم بجذوع شجر الأثل والنخيل للأسقف.
  * تتميز بوجود "المارز" لتصريف الأمطار، و"الرواشين" والفتحات الهوائية الذكية التي تلطف حرارة الصيف البدوية.

* **🧶 الأزياء والأزياء التقليدية:**
  * *الرجال:* الثوب التقليدي الواسع، وفوقه "البشت" المعمول من صوف الخروف الفاخر، والعقال المقصب أو الشماغ الأحمر بـ "الكوفية".
  * *النساء:* "البخنق" الأسود المطرز بخيوط ذهبية وفضية للبنات، و"الثوب النجدي" المزركش والمطرز باليد، إلى جانب البرقع التقليدي.

* **📜 الشعر النبطي والأهازيج:**
  * نجد موطن الشعر النبطي الأصيل وقصص الفرسان (مثل شليويح العطاوي وغيرهم).
  * *العرضة السعودية:* فن حربي جماعي يجمع بين صفوف الرجال، دقات الطبول (التكس والطار)، والتلويح بالسيوف الصقيلة والراية الخضراء.
  * *السامري:* فن طربي شجي يعتمد على الربابة والدفوف والأبيات الحزينة والغزلية العذبة.

* **☕ دلة الكيف وأعراف المجالس:**
  * صب القهوة السعودية باليد اليمنى، وتقديمها للضيف ثلاث مرات (الكيف، الضيف، السيف)، وهز الفنجان يعني الاكتفاء."""

  # نبذات عامة ومرتبة لباقي المناطق
  elif any(w in q for w in ["عسير", "أبها", "الجنوب"]):
    return (
        "### 🏔️ عسير البهية\n* **الأكل:** العريكة، المصابيب، الحنيذ على"
        " المحاذي الحجرية، والمخشوش.\n* **التراث:** القصبات الحجرية، وفن *القط"
        " العسيري* الهندسي المدرج في اليونسكو، والعرضة الجنوبية."
    )

  elif any(
      w in q for w in ["الحجاز", "جدة", "مكة", "المدينة المنورة", "الطائف"]
  ):
    return (
        "### 🌊 الحجاز التاريخي\n* **الأكل:** السليق الطائفي بالحليب والسمن،"
        " المنتو والجبات، والشوربة الحجازية.\n* **التراث:** الرواشين الخشبية في"
        " جدة التاريخية، وفن السمسمية، وملتقى الحجاج عبر التاريخ."
    )

  elif any(w in q for w in ["الشرقية", "الأحساء", "القطيف"]):
    return (
        "### 🌴 المنطقة الشرقية\n* **الأكل:** المحمر، والصالونة الحساوية،"
        " والتمود والأكلات البحرية.\n* **التراث:** واحة الأحساء للنخيل، صناعة"
        " البشت الحساوي بالزري، وفنون الغوص على اللؤلؤ (الفجري)."
    )

  elif any(w in q for w in ["الشمال", "تبوك", "الجوف"]):
    return (
        "### ⛰️ الشمال العريق\n* **الأكل:** المنسف الشمالي، والقرص، وأكلات"
        " البادية البرية.\n* **التراث:** قلعة مارد في دومة الجندل، أشجار"
        " الزيتون المعمرة، وعراقة الكرم والربابة."
    )

  else:
    return f"""### 🏛️ عبق التراث السعودي الشامل
سؤالك عن **"{query}"** يفتح الباب لثراء ثقافتنا الواسعة. 

التطبيق الآن يعطيك نظرة شاملة وسريعة على أي مدينة تسألين عنها، و**يتوسع تفصيلياً ليشمل (الأكل، العمارة، الأزياء، والشعر والأعراف) إذا وجهتِ السؤال لـ (نجد)**. تفضلي واسألي عن أي تفصيل ترغبين به!"""


# صندوق الإدخال للمستخدم
if prompt := st.chat_input(
    "اسأل عن الأكل، التراث، أو تعمق في نجد (مثل: الجريش، العرضة، الدرعية)..."
):
  st.session_state.messages.append({"role": "user", "content": prompt})
  with st.chat_message("user"):
    st.markdown(prompt)

  with st.chat_message("assistant"):
    with st.spinner("جاري إعداد السفرة واستحضار السوالف..."):
      answer = get_cultural_response(prompt)
      st.markdown(answer)
      st.session_state.messages.append({"role": "assistant", "content": answer})
